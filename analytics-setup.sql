-- Anonymous usage analytics for After Midnight.
-- Stores no names, answers, room codes, IP addresses, or account identifiers.

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  visitor_id text not null,
  session_id text not null,
  event_name text not null,
  page_key text not null,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists analytics_events_created_at_idx on public.analytics_events(created_at desc);
create index if not exists analytics_events_event_idx on public.analytics_events(event_name,page_key);
create index if not exists analytics_events_visitor_idx on public.analytics_events(visitor_id);

alter table public.analytics_events enable row level security;
revoke all on public.analytics_events from anon, authenticated;

create or replace function public.track_event(
  p_visitor_id text,
  p_session_id text,
  p_event_name text,
  p_page_key text,
  p_metadata jsonb default '{}'::jsonb
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if length(coalesce(p_visitor_id,'')) not between 8 and 64
     or length(coalesce(p_session_id,'')) not between 8 and 64 then
    return;
  end if;

  if p_event_name not in (
    'page_view','explore_click','challenge_select','card_draw',
    'answer_submit','room_create','room_join','room_start',
    'room_finish','identity_test_open'
  ) then return; end if;

  if p_page_key not in (
    'home','mystery','among','ghost','midnight','letters',
    'rewards','diy','personality','analytics'
  ) then return; end if;

  -- Drop accidental rapid duplicates without blocking normal interactions.
  if exists (
    select 1 from public.analytics_events
    where visitor_id=p_visitor_id and session_id=p_session_id
      and event_name=p_event_name and page_key=p_page_key
      and created_at > now()-interval '750 milliseconds'
  ) then return; end if;

  insert into public.analytics_events(visitor_id,session_id,event_name,page_key,metadata)
  values (left(p_visitor_id,64),left(p_session_id,64),p_event_name,p_page_key,coalesce(p_metadata,'{}'::jsonb));
end;
$$;

create or replace function public.get_analytics_summary()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with totals as (
    select count(*)::int total_events,
           count(distinct visitor_id)::int unique_visitors,
           count(distinct session_id)::int total_sessions
    from public.analytics_events
  ), pages as (
    select page_key, count(*)::int views, count(distinct visitor_id)::int visitors
    from public.analytics_events where event_name='page_view'
    group by page_key order by views desc,page_key
  ), actions as (
    select event_name,page_key,count(*)::int count
    from public.analytics_events where event_name<>'page_view'
    group by event_name,page_key order by count desc,event_name,page_key
  ), answers as (
    select page_key,count(*)::int attempts,
           count(*) filter (where metadata->>'correct'='true')::int correct
    from public.analytics_events where event_name='answer_submit'
    group by page_key order by attempts desc
  ), daily as (
    select to_char(created_at at time zone 'Asia/Hong_Kong','YYYY-MM-DD') as "day",
           count(*) filter (where event_name='page_view')::int views,
           count(distinct visitor_id)::int visitors
    from public.analytics_events
    where created_at >= now()-interval '30 days'
    group by 1 order by 1
  )
  select jsonb_build_object(
    'generated_at',now(),
    'total_events',(select total_events from totals),
    'unique_visitors',(select unique_visitors from totals),
    'total_sessions',(select total_sessions from totals),
    'pages',coalesce((select jsonb_agg(to_jsonb(pages)) from pages),'[]'::jsonb),
    'actions',coalesce((select jsonb_agg(to_jsonb(actions)) from actions),'[]'::jsonb),
    'answers',coalesce((select jsonb_agg(to_jsonb(answers)) from answers),'[]'::jsonb),
    'daily',coalesce((select jsonb_agg(to_jsonb(daily)) from daily),'[]'::jsonb)
  );
$$;

revoke all on function public.track_event(text,text,text,text,jsonb) from public;
revoke all on function public.get_analytics_summary() from public;
grant execute on function public.track_event(text,text,text,text,jsonb) to anon, authenticated;
grant execute on function public.get_analytics_summary() to anon, authenticated;

